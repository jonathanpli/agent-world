const FALLBACK = GLYPHS["?"]!;

export const FONT = { h: 6, capH: 5, spacing: 1 } as const;

const glyph = (ch: string): string[] => GLYPHS[ch] ?? FALLBACK;

export function textWidth(text: string): number {
  let w = 0;
  for (const ch of text) w += glyph(ch)[0]!.length + FONT.spacing;
  return Math.max(0, w - FONT.spacing);
}

/** Cuts `text` with "…" so it fits in `maxW` pixels. */
export function fitText(text: string, maxW: number): string {
  if (textWidth(text) <= maxW) return text;
  const chars = [...text];
  while (chars.length > 0 && textWidth(chars.join("") + "…") > maxW) chars.pop();
  return chars.join("") + "…";
}

/** Draws `text` with its top-left at (x, y); returns the x after the last glyph. */
export function drawText(ctx: Ctx, text: string, x: number, y: number, color: string): number {
  ctx.fillStyle = color;
  let cx = Math.round(x);
  const cy = Math.round(y);
  for (const ch of text) {
    const rows = glyph(ch);
    for (let r = 0; r < rows.length; r++) {
      const row = rows[r]!;
      let c = 0;
      while (c < row.length) {
        if (row[c] !== "#") { c++; continue; }
        let end = c + 1;
        while (end < row.length && row[end] === "#") end++;
        ctx.fillRect(cx + c, cy + r, end - c, 1);
        c = end;
      }
    }
    cx += rows[0]!.length + FONT.spacing;
  }
  return cx - FONT.spacing;
}
